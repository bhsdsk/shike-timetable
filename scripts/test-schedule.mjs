import assert from 'node:assert/strict';
import ts from 'typescript';
import {readFileSync} from 'node:fs';
const js=ts.transpile(readFileSync('lib/schedule.ts','utf8'),{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022});
const m=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const courses=JSON.parse(readFileSync('lib/seed.json','utf8'));
assert.deepEqual(courses,[],'New users start empty');
const course={id:'a',name:'测试课程',code:'TEST',teacher:'教师',room:'教室',category:'自定义',notes:'',day:2,start:1,end:2,weeks:[2,10]};
assert.equal(m.validateSchedule({courses:[course],settings:m.defaultSettings}),true);
assert.equal(m.endTime('08:00',40),'08:40');assert.equal(m.endTime('21:00',60),'22:00');
assert.equal(m.dateFor('2026-09-07',2,7).getDate(),20);
assert.equal(m.weekLabel([2,10]),'2、10 周');
for(const w of [0,31,1.5])assert.equal(m.validateSchedule({courses:[{...course,weeks:[w]}],settings:m.defaultSettings}),false);
for(const item of [null,{},42])assert.equal(m.validateSchedule({courses:[item],settings:m.defaultSettings}),false);
assert.equal(m.validateSchedule({courses,settings:{...m.defaultSettings,firstMonday:'2026-09-08'}}),false);
assert.equal(m.validateSchedule({courses,settings:{...m.defaultSettings,times:Array(14).fill('08:00')}}),false);
assert.equal(m.validateSchedule({courses:[{...course,end:3}],settings:{...m.defaultSettings,morning:2,afternoon:0,times:['08:00','09:00']}}),false,'Cannot hide existing courses by reducing periods');
assert.equal(m.validateSchedule({courses,settings:{...m.defaultSettings,morning:3,afternoon:2,duration:40,times:['08:00','08:45','09:30','13:00','13:45']}}),true);
const overlapping=[course,{...course,id:'b',start:2,end:3},{...course,id:'c',start:3,end:4}];const lanes=m.courseLanes(overlapping);assert.notEqual(lanes.a.lane,lanes.b.lane);assert.notEqual(lanes.b.lane,lanes.c.lane);assert.equal(lanes.a.count,2);
console.log('PASS: empty defaults, configurable periods/duration, week dates, disjoint weeks, conflict lanes and input validation.');
